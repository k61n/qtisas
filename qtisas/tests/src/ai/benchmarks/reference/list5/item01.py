t = newTable("Calib", 21, 3)
t.setColNames(["x", "y", "dy"])
t.setColumnRole(1, Table.PlotDesignation.X)
t.setColumnRole(2, Table.PlotDesignation.Y)
t.setColumnRole(3, Table.PlotDesignation.yErr)
t.setColData(1, [0.1*i for i in range(21)])
t.setCommand("y", '3*col("x")**2 - 2*col("x") + 1')  # Python: ** for a power, ^ is XOR
t.recalculate("y")
t.setColData(3, [0.05]*21)
c = Compiler
c.new()
c.setFunctionName("ai/Quad")
c.setGroup("reference")
c.setXName("x")
c.setYName("y")
c.setParamCount(3)
c.setParamNamesAll(["a", "b", "c"])
c.setParamInitsAll([1.0, 1.0, 1.0])
c.setParamVariesAll([True, True, True])
c.setCode("y = a*x*x + b*x + c;")
c.compile()
f = Fittable
f.configure("ai/Quad", ["Calib_y"])
for name in ("a", "b", "c"):
    f.setParamValue(name, 1.0)
f.setWeightingEnabled(1, True)
f.setWeightingDataset(1, "Calib_dy")
f.fit()
r = f.results()
above = sum(1 for v in t.colData("y") if v > 5)
scriptPrint("R1: %.4f %.4f %.4f %d" % (r["a"][0], r["b"][0], r["c"][0], above))
