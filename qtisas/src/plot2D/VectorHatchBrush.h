#ifndef VECTORHATCHBRUSH_H
#define VECTORHATCHBRUSH_H

#include <Qt>

class QPainter;
class QPainterPath;
class QColor;
class QByteArray;

namespace VectorHatchBrush
{
//! True for the builtin styles this namespace can replace (Dense1-7, Hor/Ver/Cross/BDiag/FDiag/DiagCross).
bool isHatchStyle(Qt::BrushStyle style);

//! Fills path with a vector approximation of style (lines, or a dot grid for Dense* levels), clipped via
//! geometric intersection rather than painter clipping. spacing is the tile pitch; pass a smaller value
//! for a small area (e.g. a legend swatch) than the default full-size pitch.
//!
//! For Dense1-7 during SVG export, fills with a marker color instead and registers the real
//! (color, style, spacing); call applyPatternRegistry() on the generated bytes to resolve it.
void fillPath(QPainter *painter, const QPainterPath &path, const QColor &color, Qt::BrushStyle style,
              double spacing = 4.0);

//! Clears the marker registry. Call once before the first pass of a whole export, not per pass/layer
//! -- indices must stay unique across every pass merged into one output document.
void resetPatternRegistry();

//! Replaces marker-colored fills in svg with references to an injected <pattern>. Call on each pass's
//! bytes right after generating them, before merging with any other pass.
QByteArray applyPatternRegistry(const QByteArray &svg);

//! PDF analog of applyPatternRegistry(): given a finished QPdfWriter-produced PDF's bytes, returns
//! those bytes with marker-colored fills replaced by real PDF /Pattern references. grayscale also
//! desaturates every other color operator in the document (QPdfWriter has no color-mode concept).
QByteArray applyPatternRegistryPdf(const QByteArray &pdf, bool grayscale = false);
} // namespace VectorHatchBrush

#endif // VECTORHATCHBRUSH_H
