c = Compiler
c.new()
c.setFunctionName("ai/RefDecay")
c.setGroup("reference")
c.setXName("x")
c.setYName("y")
c.setParamCount(3)
c.setParamNamesAll(["A", "k", "c"])
c.setParamInitsAll([1.0, 1.0, 0.0])
c.setParamVariesAll([True, True, True])
c.setCode("y = A*exp(-k*x) + c;")
c.compile()
t = newTable("DecayData", 101, 3)
t.setColNames(["x", "y", "dy"])
t.setColumnRole(1, Table.PlotDesignation.X)
t.setColumnRole(2, Table.PlotDesignation.Y)
t.setColumnRole(3, Table.PlotDesignation.yErr)
xs = [0.1*i for i in range(101)]
t.setColData(1, xs)
t.setColData(2, [3*exp(-0.5*x) + 0.2 for x in xs])
t.setColData(3, [0.01]*101)
f = Fittable
f.configure("ai/RefDecay", ["DecayData_y"])
f.setParamValue("A", 1.0)
f.setParamValue("k", 1.0)
f.setParamValue("c", 0.0)
f.setWeightingEnabled(1, True)
f.setWeightingDataset(1, "DecayData_dy")
f.fit()
r = f.results()
scriptPrint("R8: %.4f %.4f %.4f" % (r["A"][0], r["k"][0], r["c"][0]))
