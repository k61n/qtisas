newNote("Log")
t = newTable("Metrics", 20, 3)
t.setColNames(["x", "y", "z"])
t.setColumnRole(1, Table.PlotDesignation.X)
t.setColumnRole(2, Table.PlotDesignation.Y)
t.setColumnRole(3, Table.PlotDesignation.Z)
xs = list(range(1, 21))
t.setColData(1, xs)
t.setColData(2, [21 - x for x in xs])
t.setColData(3, [x * (21 - x) for x in xs])
gw = newGraph("MetricsPlot")
layer = gw.activeLayer()
layer.insertCurve(t, "x", "y", Graph.CurveType.LineSymbols)
layer.setCurveLineColor(0, colorIndex("blue"))
layer.setXTitle("x")
layer.setYTitle("y")
leg = layer.legend() or layer.newLegend()
