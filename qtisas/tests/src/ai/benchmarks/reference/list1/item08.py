c = Compiler
c.new()
c.setFunctionName("ai/Porod")
c.setGroup("reference")
c.setXName("q")
c.setYName("I")
c.setParamCount(3)
c.setParamNamesAll(["scale", "n", "background"])
c.setParamInitsAll([1.0, 4.0, 0.0])
c.setParamVariesAll([True, True, True])
c.setCode("I = scale*pow(q,-n) + background;")
c.compile()
f = Fittable
f.configure("ai/Porod", [])
f.selectStage("simulate")
for p, v in (("scale", 1.0), ("n", 4.0), ("background", 0.0)):
    f.setParamValue(p, v)
f.setSimUniformX(True)
f.setSimFromX(0.01)
f.setSimToX(1.0)
f.setSimNumPoints(100)
f.setSimLogStep(True)
f.simulateCurve()
s = table("simulatedCurve-ai/Porod")
scriptPrint("R8: %d %g" % (s.numRows(), s.cell(2, 1)))
