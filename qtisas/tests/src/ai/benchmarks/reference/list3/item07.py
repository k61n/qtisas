c = Compiler
c.new()
c.setFunctionName("ai/RefLine")
c.setGroup("reference")
c.setXName("x")
c.setYName("y")
c.setParamCount(2)
c.setParamNamesAll(["a", "b"])
c.setParamInitsAll([1.0, 0.0])
c.setParamVariesAll([True, True])
c.setCode("y = a*x + b;")
c.compile()
t = newTable("LineData", 20, 3)
t.setColNames(["x", "y", "dy"])
t.setColumnRole(1, Table.PlotDesignation.X)
t.setColumnRole(2, Table.PlotDesignation.Y)
t.setColumnRole(3, Table.PlotDesignation.yErr)
t.setColData(1, range(1, 21))
t.setColData(2, [2*x + 1 for x in range(1, 21)])
t.setColData(3, [0.1]*20)
f = Fittable
f.configure("ai/RefLine", ["LineData_y"])
f.setFitMethod("LM")
f.setWeightingEnabled(1, True)
f.setWeightingDataset(1, "LineData_dy")
f.fit()
r = f.results()
scriptPrint("R7: %.4f %.4f" % (r["a"][0], r["b"][0]))
